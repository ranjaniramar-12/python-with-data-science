student_name = "Arun"
age = 21
print("Student Name:", student_name)
print("Age:", age)

marks = [80, 85, 90, 75, 95]
print("Marks:", marks)
print("Total Marks:", sum(marks))
print("Average Marks:", sum(marks) / len(marks))

print("\nIndividual Marks:")
for mark in marks: print(mark)

average = sum(marks) / len(marks)
if average >= 50:
  print("Result: Pass")
else:
  print("Result: Fail")

def calculate_average(numbers): return sum(numbers) / len(numbers)
print("Calculated Average:", calculate_average(marks))

student = { "name": student_name, "age": age, "marks": marks }
print("Student Details:", student)

with open("student_results.txt", "w") as file:
    file.write("Student Marks Analysis\n")
    file.write(f"Student Name: {student_name}\n")
    file.write(f"Age: {age}\n")
    file.write(f"Marks: {marks}\n")
    file.write(f"Average: {average}\n")

print("Results saved to student_results.txt")

